#!/usr/bin/env python3
"""Collect distinct handheld boots over SSH and compare non-overlapping stages."""
import argparse
import json
from pathlib import Path
import re
import statistics
import subprocess
import time


def watch(args):
    args.output.mkdir(parents=True, exist_ok=True)
    ssh = ['ssh', '-i', str(args.key), '-o', 'BatchMode=yes', '-o', 'ConnectTimeout=3', args.host]
    def retained():
        p = subprocess.run(ssh + ["find /storage/slotcontent/Diagnostics/BootProfiles -maxdepth 1 -name 'boot-*.json'"], capture_output=True, text=True, timeout=8)
        if p.returncode:
            return None
        return {match[1] for line in p.stdout.splitlines()
                if (match := re.fullmatch(r'/storage/slotcontent/Diagnostics/BootProfiles/boot-([a-f0-9-]{36})\.json', line))}
    baseline = retained()
    if baseline is None:
        raise SystemExit('Connect the handheld before starting a new boot watch.')
    seen = set(args.ignore_boot) | (set() if args.include_existing else baseline)
    captured = 0
    deadline = time.monotonic() + args.timeout
    while time.monotonic() < deadline and captured < args.count:
        try:
            available = retained()
            pending = sorted((available or set()) - seen)
            if not pending:
                time.sleep(5)
                continue
            boot = pending[0]
            base = '/storage/slotcontent/Diagnostics/BootProfiles/boot-' + boot
            p = subprocess.run(ssh + ['cat ' + base + '.json'], capture_output=True, timeout=8)
            if p.returncode or not 0 < len(p.stdout) <= 2 * 1024 * 1024:
                time.sleep(5)
                continue
            report = json.loads(p.stdout)
            if report.get('boot_id') != boot or report.get('schema') != 1:
                raise ValueError('Boot report identity/schema mismatch')
            (args.output / ('boot-' + boot + '.json')).write_bytes(p.stdout)
            for suffix in ('md', 'csv', 'svg'):
                p = subprocess.run(ssh + ['cat ' + base + '.' + suffix], capture_output=True, timeout=8)
                if p.returncode == 0 and len(p.stdout) <= 2 * 1024 * 1024:
                    (args.output / ('boot-' + boot + '.' + suffix)).write_bytes(p.stdout)
            seen.add(boot)
            captured += 1
            print(json.dumps({'captured': captured, 'boot_id': boot, 'first_scene_swap_s': report['summary']['first_scene_swap_s']}), flush=True)
        except (subprocess.TimeoutExpired, json.JSONDecodeError):
            pass
        time.sleep(5)
    if captured != args.count:
        raise SystemExit(f'Collected {captured}/{args.count} distinct boots; timeout reached. Existing captures retained.')


def compare(args):
    reports = [json.loads(p.read_text()) for p in args.reports]
    if len({r['boot_id'] for r in reports}) != len(reports):
        raise ValueError('Duplicate boot IDs cannot count as repeated boots')
    if any(r.get('clock') != 'CLOCK_MONOTONIC' for r in reports):
        raise ValueError('Mixed or missing clocks')
    observations = json.loads(args.observations.read_text()) if args.observations else {}
    print('# RG353V boot comparison\n')
    print('| Boot ID | Classification | Kernel → first scene, s | Rumble → shelf, s | Residual before kernel*, s |')
    print('|---|---|---:|---:|---:|')
    for report in reports:
        boot = report['boot_id']
        shelf = report['summary']['first_scene_swap_s']
        note = observations.get(boot, {})
        manual = note.get('rumble_to_shelf_s')
        # This residual is an external estimate, never a firmware trace.
        residual = manual - shelf if manual is not None and shelf is not None else None
        values = [shelf, manual, residual]
        print('| ' + boot + ' | ' + note.get('kind', 'unclassified') + ' | ' + ' | '.join('unmeasured' if v is None else f'{v:.3f}' for v in values) + ' |')
    print('\n*Residual includes stopwatch reaction and panel presentation error. The rumble is generated by U-Boot before Linux; this estimate requires matched observations from the same boot.\n')
    print('| Non-overlapping stage | Median s | Minimum s | Maximum s | Samples |')
    print('|---|---:|---:|---:|---:|')
    stages = {}
    for report in reports:
        for row in report['summary']['stages']:
            if row['duration_s'] is not None:
                stages.setdefault(row['name'], []).append(row['duration_s'])
    for name, values in stages.items():
        print(f'| {name} | {statistics.median(values):.3f} | {min(values):.3f} | {max(values):.3f} | {len(values)} |')
    for key, title in [('init_steps', 'Initramfs/hardware scripts'), ('frontend_steps', 'Frontend')]:
        stages = {}
        for report in reports:
            for row in report['summary'][key]:
                if row['duration_s'] is not None:
                    stages.setdefault(row['name'], []).append(row['duration_s'])
        print('\n## ' + title + '\n\n| Step | Median s | Minimum s | Maximum s | Samples |\n|---|---:|---:|---:|---:|')
        for name, values in sorted(stages.items(), key=lambda pair: statistics.median(pair[1]), reverse=True):
            print(f'| {name} | {statistics.median(values):.3f} | {min(values):.3f} | {max(values):.3f} | {len(values)} |')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest='command', required=True)
    w = sub.add_parser('watch')
    w.add_argument('--host', required=True)
    w.add_argument('--key', type=Path, required=True)
    w.add_argument('--output', type=Path, required=True)
    w.add_argument('--include-existing', action='store_true', help='Also collect retained reports already present at startup')
    w.add_argument('--count', type=int, default=3)
    w.add_argument('--timeout', type=int, default=1200)
    w.add_argument('--ignore-boot', action='append', default=[])
    c = sub.add_parser('compare')
    c.add_argument('reports', type=Path, nargs='+')
    c.add_argument('--observations', type=Path)
    args = p.parse_args()
    if args.command == 'watch':
        watch(args)
    else:
        compare(args)
