#!/usr/bin/env bash
set -euo pipefail
source_tree=${1:?Use a prepared ROCKNIX source directory}
source_tree=$(cd "$source_tree" && pwd)
cache=$(cd "$source_tree/../../cache/rocknix.git" && pwd)
build_lock="$source_tree/../../.rocknix-build.lock"
mkdir "$build_lock" 2>/dev/null || { echo 'Another ROCKNIX build holds the shared cache lock.' >&2; exit 1; }
trap 'rmdir "$build_lock"' EXIT
host_arch=$(docker info --format '{{.Architecture}}')
read -r build_profile debug_packages < <(python3 - "$source_tree" <<'PYTHON'
import json,sys
from pathlib import Path
root=Path(sys.argv[1]);path=root/'.rg353v-profile.json'
if path.exists():
 p=json.loads(path.read_text());name=p['profile'];debug=p['debug_packages']
 assert name in ('normal','development') and debug==('no' if name=='normal' else 'yes')
 factory=json.loads((root/'projects/ROCKNIX/devices/RK3566/packages/slot-rg353v/config/os-profile.json').read_text())
 assert factory['build_profile']==name and factory['layer_sha256']==p['layer_sha256']
 print(name,debug)
else:print('legacy','yes')
PYTHON
)
[[ -n $build_profile && -n $debug_packages ]] || { echo 'Invalid staged build profile.' >&2; exit 2; }
build_started=$(date +%s)
make_jobs=${RG353V_BUILD_JOBS:-2}
load_limit=${RG353V_BUILD_LOAD:-2}
case "$host_arch" in
    aarch64|arm64)
        platform=linux/arm64
        volume=slot-rocknix-rg353v-arm-builder
        dockerfile_hash=$(shasum -a 256 "$source_tree/Dockerfile" | awk '{print $1}')
        recorded=$(docker image inspect slot-rocknix-builder:arm64 --format '{{index .Config.Labels "rg353v.builder-source"}}' 2>/dev/null || true)
        if [[ $recorded != "$dockerfile_hash" ]]; then
            docker build --platform "$platform" --label "rg353v.builder-source=$dockerfile_hash" \
                -t slot-rocknix-builder:arm64 -f "$source_tree/Dockerfile" "$source_tree"
        fi
        builder=$(docker image inspect slot-rocknix-builder:arm64 --format '{{.Id}}')
        ;;
    x86_64|amd64)
        platform=linux/amd64
        volume=slot-rocknix-rg353v-builder
        builder=ghcr.io/rocknix/rocknix-build@sha256:2c6dca726ed2417cd0f56b7244598150af816cc5c198d2413841cc0b1e445246
        ;;
    *) echo "Unsupported builder architecture: $host_arch" >&2; exit 2 ;;
esac
docker volume create "$volume" >/dev/null
# All compilation happens on Linux ext4, avoiding macOS bind-mount semantics.
docker run --rm --platform "$platform" --user 0 \
    -v "$volume:/work" -v "$source_tree:/seed:ro" -v "$cache:/cache:ro" \
    -e GIT_CONFIG_COUNT=2 -e GIT_CONFIG_KEY_0=safe.directory -e GIT_CONFIG_VALUE_0=/work/rocknix \
    -e GIT_CONFIG_KEY_1=safe.directory -e GIT_CONFIG_VALUE_1=/cache \
    "$builder" bash -ec '
      if [ ! -d /work/rocknix/.git ]; then
        git clone --shared --no-checkout /cache /work/rocknix
      fi
      test ! -e /work/rocknix/.building || { echo "A build is already running." >&2; exit 1; }
      # Remove only obsolete generated profile wrappers from an earlier layout.
      for name in image network; do
        obsolete=/work/rocknix/projects/ROCKNIX/devices/RK3566/packages/$name/package.mk
        if [ -f "$obsolete" ] && grep -q "^# Generated RG353V profile overlay;" "$obsolete"; then
          rm "$obsolete"
          rmdir "${obsolete%/*}"
        fi
      done
      # Remove only wrappers from the rejected early userspace experiment.
      # Project and device packages occupy the same ROCKNIX local namespace.
      for name in SDL2 SDL2_glesonly; do
        obsolete=/work/rocknix/projects/ROCKNIX/devices/RK3566/packages/$name
        if [ -f "$obsolete/package.mk" ] && grep -q "^# Generated RG353V userspace override;" "$obsolete/package.mk"; then
          rm -rf "$obsolete"
        fi
      done
      rsync -a --no-owner --no-group --exclude=/.git --exclude=/.env --exclude=/release --exclude=/target --exclude="/build.*" /seed/ /work/rocknix/
      # A baseline seed must not inherit the opt-in internal-display DTS patch
      # from a prior slim build in this shared cache.
      for patch_name in 1013-slot-rg353v-internal-display.patch 1014-slot-rg353v-rtw88-regulatory.patch; do
        managed_patch=projects/ROCKNIX/devices/RK3566/patches/linux/$patch_name
        if [ ! -f "/seed/$managed_patch" ]; then rm -f "/work/rocknix/$managed_patch"; fi
      done
      # These packages are wholly generated by the managed layer. The broad
      # sync retains build caches, so separately delete stale package sources
      # (for example removed experimental units) before hashing/building them.
      for package in slot-rg353v slot-startup-profile slot-bootsplash; do
        managed=projects/ROCKNIX/devices/RK3566/packages/$package
        test -f /seed/$managed/package.mk
        rsync -a --delete --no-owner --no-group /seed/$managed/ /work/rocknix/$managed/
      done
      cp /seed/.git/HEAD /work/rocknix/.git/HEAD
      git -C /work/rocknix read-tree HEAD
      rm -f /work/rocknix/build.ROCKNIX-RK3566.aarch64/.cache_package_global /work/rocknix/build.ROCKNIX-RK3566.aarch64/.cache_package_local
      chown -R 1000:1000 /work/rocknix
    '
docker run --rm --init --platform "$platform" --name slot-rocknix-mini-build \
    -v "$volume:/work" -v "$cache:/cache:ro" -w /work/rocknix \
    -e SLOT_RG353V_PROFILE="$build_profile" -e DEBUG_PACKAGES="$debug_packages" \
    -e BASE_ONLY=true -e CONCURRENCY_MAKE_LEVEL="$make_jobs" -e CONCURRENCY_LOAD="$load_limit" -e PROJECT=ROCKNIX -e DEVICE=RK3566 -e DEVICE_ROOT=RK3566 -e ARCH=aarch64 \
    -e GIT_CONFIG_COUNT=2 -e GIT_CONFIG_KEY_0=safe.directory -e GIT_CONFIG_VALUE_0=/work/rocknix \
    -e GIT_CONFIG_KEY_1=safe.directory -e GIT_CONFIG_VALUE_1=/cache \
    "$builder" bash -ec '
      trap "rm -f .building" EXIT
      touch .building
      ./scripts/build_distro
    '
mkdir -p "$source_tree/release"
docker run --rm --platform "$platform" --user 0 \
    -v "$volume:/work:ro" -v "$source_tree/release:/release" -e OUTPUT_UID="$(id -u)" -e OUTPUT_GID="$(id -g)" "$builder" \
    bash -ec 'cp -a /work/rocknix/target/*.img.gz /work/rocknix/target/*.tar /release/; chown -R "$OUTPUT_UID:$OUTPUT_GID" /release'
build_elapsed=$(( $(date +%s) - build_started ))
docker run --rm --platform "$platform" --user 0 \
    -v "$volume:/work:ro" -v "$source_tree/release:/output" -v "$PWD:/src:ro" \
    "$builder" python3 /src/scripts/record-rg353v-build.py \
    --tree /work/rocknix --profile "$build_profile" --seconds "$build_elapsed" --output /output/build-report.json
echo "Firmware artifacts: $source_tree/release ($build_profile, ${build_elapsed}s)"
